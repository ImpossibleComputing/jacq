//! CUDA code generation for the Jacquard model DSL.
//!
//! Emits a self-contained CUDA C++ inference runtime and a Python weight-export script from a
//! lowered [`jac_ir::ModelIr`]. Phase 0 targets TinyLlama-class fp16 LLaMA-family models
//! (RMSNorm, fused QKV, RoPE, GQA attention with KV cache, SiLU-gated FFN, greedy sampling).

