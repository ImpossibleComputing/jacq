/// Sink + recent-window selection policy (track B, M1).
/// `sink_s = 0, window_w = u32::MAX` ⇒ exact attention (mask is a no-op).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct SelectionPolicy {
    pub sink_s: u32,
    pub window_w: u32,
}

impl SelectionPolicy {
    /// The exact-attention policy (default, no masking).
    pub const fn exact() -> Self {
        SelectionPolicy {
            sink_s: 0,
            window_w: u32::MAX,
        }
    }
}

